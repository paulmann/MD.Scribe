#Requires -Version 7.6
#Requires -PSEdition Core

<#
.SYNOPSIS
    Project-doctrine checker for MD.Scribe.

.DESCRIPTION
    Verifies the conventions this repository actually follows. Every rule names
    the file that proves it, so a failure can be traced to code rather than to
    taste. Read-only: nothing is written and no PHP is executed.

    Checks:
      1. repository layout - the anchor files the documentation names still exist
      2. version consistency - Version.php = CHANGELOG.md = README.md
      3. strict types - every src/ PHP file declares strict_types=1
      4. PHPStan ratchet - level 6, and no new ignoreErrors entries
      5. CI gates - lint, phpstan, phpunit and the smoke curl are still wired
      6. secret hygiene - no secret-shaped file outside the recorded baseline
      7. wikilink contract - parser/renderer registered, toggle in the render
         fingerprint, sanitizer keeps the marker class
      8. render-cache contract - the corpus stamp joins the cache key, so a new
         document invalidates cached wikilink states
      9. release manifest - advisory: warns while config/manifest.json is older
         than the code (regenerated by tools/build-manifest.php at release time)

.PARAMETER ProjectRoot
    Repository root. Defaults to the parent directory of this script, which is
    correct when the file sits in the project's tools directory.

.PARAMETER MaxExamples
    How many examples to print per failed check. Defaults to 10.

.PARAMETER Strict
    Treat warnings as errors.

.EXAMPLE
    pwsh -NoLogo -NoProfile -NonInteractive -File .\Invoke-ProjectDoctrine.ps1

.EXAMPLE
    pwsh -NoLogo -NoProfile -NonInteractive -File .\Invoke-ProjectDoctrine.ps1 -Strict
#>

[CmdletBinding()]
param(
    [string] $ProjectRoot = (Split-Path -Parent $PSScriptRoot),
    [int] $MaxExamples = 10,
    [switch] $Strict
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$script:ProjectRoot = [System.IO.Path]::GetFullPath($ProjectRoot)
if (-not (Test-Path -LiteralPath $script:ProjectRoot -PathType Container)) {
    throw "Project root not found: $script:ProjectRoot"
}
$script:MaxExamples = $MaxExamples

# --------------------------------------------------------------- exclusions

# Directories that are not the project's own code. `.zwork`, `.dev_agent` and
# `.work` are agent scratch directories: they hold snapshots and staging copies
# of earlier runs, including stale copies of this very file, so reading them
# produces findings about code that no longer exists.
$script:CodeExclusionPattern = '\\(?:\.git|\.zwork|\.dev_agent|\.work|vendor|node_modules|bower_components|__pycache__|\.venv|dist|build|coverage)\\'

# Secrets are scanned with a NARROW exclusion: a secret-shaped file can sit
# inside an asset directory, so reusing the pattern above would blind the check.
$script:SecretExclusionPattern = '\\(?:\.git|\.zwork|\.dev_agent|\.work)\\'

# --------------------------------------------------------------- framework

function Test-RegexLiteral {
    param([Parameter(Mandatory)][string] $Pattern)

    try { $null = [regex]::new($Pattern); return $true }
    catch { return $false }
}

function Assert-RegexLiteral {
    param(
        [Parameter(Mandatory)][string] $Pattern,
        [Parameter(Mandatory)][string] $What
    )

    if (Test-RegexLiteral -Pattern $Pattern) { return }
    throw "invalid regex for ${What}: $Pattern"
}

function Get-RelativePath {
    param([Parameter(Mandatory)][string] $FullPath)

    return ([System.IO.Path]::GetRelativePath($script:ProjectRoot, $FullPath)) -replace '\\', '/'
}

function Get-RepositoryFile {
    param(
        [string[]] $Extension = @(),
        [switch] $IncludeHidden,
        [switch] $SecretScan
    )

    $pattern = if ($SecretScan) { $script:SecretExclusionPattern } else { $script:CodeExclusionPattern }
    Assert-RegexLiteral -Pattern $pattern -What 'repository file exclusion'

    $items = Get-ChildItem -LiteralPath $script:ProjectRoot -Recurse -File -Force:$IncludeHidden -ErrorAction SilentlyContinue
    $result = [System.Collections.Generic.List[System.IO.FileInfo]]::new()

    foreach ($file in $items) {
        if ($file.FullName -match $pattern) { continue }
        if ($Extension.Count -gt 0 -and $Extension -notcontains $file.Extension.ToLowerInvariant()) { continue }
        $result.Add($file)
    }

    return $result
}

function Get-ProjectText {
    param([Parameter(Mandatory)][string] $RelativePath)

    $full = Join-Path $script:ProjectRoot $RelativePath
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { return $null }

    return [System.IO.File]::ReadAllText($full)
}

function New-CheckResult {
    param(
        [Parameter(Mandatory)][string] $Name,
        [Parameter(Mandatory)][bool] $Ok,
        [int] $Examined = -1,
        [string[]] $Details = @(),
        [switch] $Warning,
        [string] $NotApplicable
    )

    $detailList = [System.Collections.Generic.List[string]]::new()
    foreach ($detail in $Details) { $detailList.Add($detail) }

    $kind = 'error'
    if ($NotApplicable) { $kind = 'na' }
    elseif ($Ok) {
        if ($Examined -le 0) {
            # The defect this framework exists to catch.
            $Ok = $false
            $kind = 'void'
            $detailList.Insert(0, 'FALSE PASS: проверка сообщила Ok, но не осмотрела ни одного объекта (-Examined = ' + $Examined + ')')
        }
        else { $kind = 'pass' }
    }
    elseif ($Warning) { $kind = 'warn' }

    [pscustomobject]@{
        Name     = $Name
        Ok       = $Ok
        Examined = $Examined
        Details  = @($detailList)
        Warning  = [bool] $Warning
        Kind     = $kind
    }
}

function Write-CheckResult {
    param([Parameter(Mandatory)][pscustomobject] $Check)

    $label = switch ($Check.Kind) {
        'pass' { '[PASS]' }
        'na'   { '[N/A] ' }
        'warn' { '[WARN]' }
        default { '[FAIL]' }
    }
    $color = switch ($Check.Kind) {
        'pass' { 'Green' }
        'na'   { 'DarkGray' }
        'warn' { 'Yellow' }
        default { 'Red' }
    }

    $suffix = ''
    if ($Check.Examined -ge 0) { $suffix = "  (examined $($Check.Examined))" }

    $padding = 0
    foreach ($name in $script:CheckNames) { if ($name.Length -gt $padding) { $padding = $name.Length } }

    Write-Host ($label + ' ' + $Check.Name.PadRight($padding) + $suffix) -ForegroundColor $color

    $shown = @($Check.Details | Select-Object -First $script:MaxExamples)
    foreach ($detail in $shown) { Write-Host "         $detail" }
    if ($Check.Details.Count -gt $shown.Count) {
        Write-Host "         ... и ещё $($Check.Details.Count - $shown.Count)"
    }
}

# -------------------------------------------------- startup self-guard

foreach ($guard in @(
        @{ Pattern = $script:CodeExclusionPattern; What = 'code exclusions' },
        @{ Pattern = $script:SecretExclusionPattern; What = 'secret exclusions' })) {
    Assert-RegexLiteral -Pattern $guard.Pattern -What $guard.What
}

# ------------------------------------------------------------------ checks

function Test-ProjectLayout {
    <#
    .SYNOPSIS
        The repository still looks like the project the documentation describes.

    .DESCRIPTION
        Guards against running this checker against a moved or restructured
        tree, which would otherwise report a clean sweep of an empty subject.
        The list is the set of files the guides send a reader to.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0

    $expected = @(
        'composer.json',
        'phpunit.xml',
        'phpstan.neon',
        '.github/workflows/ci.yml',
        'src/bootstrap.php',
        'src/Core/Version.php',
        'src/Core/App.php',
        'src/Http/FrontController.php',
        'src/Http/AdminKernel.php',
        'src/Files/PathValidator.php',
        'src/Markdown/MarkdownEngine.php',
        'src/Markdown/Extensions/MdViewerExtension.php',
        'public/index.php',
        'public/admin.php',
        'templates/layout/app.php',
        'templates/layout/admin.php',
        'docs/AGENTS-context.md',
        'tools/Invoke-ProjectDoctrine.ps1'
    )

    foreach ($relative in $expected) {
        $examined++
        if (-not (Test-Path -LiteralPath (Join-Path $script:ProjectRoot $relative) -PathType Leaf)) {
            $problems.Add("missing: $relative")
        }
    }

    return New-CheckResult -Name 'repository layout matches the documented tree' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-VersionConsistency {
    <#
    .SYNOPSIS
        Version.php, CHANGELOG.md and README.md agree on one version.

    .DESCRIPTION
        A release is three edits; forgetting one is invisible until a reader
        trusts the wrong number. The research on 2026-11-13 found README claiming
        3.2.2 while the code said 3.2.3 - exactly this drift.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0
    $sources = [System.Collections.Generic.List[object]]::new()

    $versionSource = Get-ProjectText 'src/Core/Version.php'
    if ($null -ne $versionSource) {
        $match = [regex]::Match($versionSource, "VERSION\s*=\s*'([0-9]+\.[0-9]+\.[0-9]+)'")
        if ($match.Success) { $sources.Add([pscustomobject]@{ Name = 'src/Core/Version.php'; Version = $match.Groups[1].Value }) }
        else { $problems.Add('src/Core/Version.php: VERSION constant not found') }
    }
    else { $problems.Add('src/Core/Version.php: file missing') }

    $changelog = Get-ProjectText 'CHANGELOG.md'
    if ($null -ne $changelog) {
        $match = [regex]::Match($changelog, '(?m)^##\s+([0-9]+\.[0-9]+\.[0-9]+)')
        if ($match.Success) { $sources.Add([pscustomobject]@{ Name = 'CHANGELOG.md'; Version = $match.Groups[1].Value }) }
        else { $problems.Add('CHANGELOG.md: no "## x.y.z" heading') }
    }
    else { $problems.Add('CHANGELOG.md: file missing') }

    $readme = Get-ProjectText 'README.md'
    if ($null -ne $readme) {
        $match = [regex]::Match($readme, 'Version:\s*([0-9]+\.[0-9]+\.[0-9]+)')
        if ($match.Success) { $sources.Add([pscustomobject]@{ Name = 'README.md'; Version = $match.Groups[1].Value }) }
        else { $problems.Add('README.md: no "Version: x.y.z" line') }
    }
    else { $problems.Add('README.md: file missing') }

    $examined = $sources.Count
    if ($sources.Count -gt 0) {
        $reference = $sources[0].Version
        foreach ($source in $sources) {
            if ($source.Version -ne $reference) {
                $problems.Add("$($source.Name) says $($source.Version), $($sources[0].Name) says $reference")
            }
        }
    }

    return New-CheckResult -Name 'version is consistent across its three carriers' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-StrictTypes {
    <#
    .SYNOPSIS
        Every PHP file under src/ declares strict_types=1.

    .DESCRIPTION
        Templates are exempt (they run inside the view sandbox and were never
        strict); src/ is not. A file without the declaration silently changes
        type-juggling behaviour for every function it defines.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0

    $files = Get-RepositoryFile -Extension @('.php') | Where-Object {
        (Get-RelativePath $_.FullName) -like 'src/*'
    }

    foreach ($file in $files) {
        $examined++
        $text = [System.IO.File]::ReadAllText($file.FullName)
        $relative = Get-RelativePath $file.FullName

        # The declaration may sit below a long licence/docblock header, so the
        # whole file is searched; it only has to come before the namespace.
        $declaration = [regex]::Match($text, 'declare\s*\(\s*strict_types\s*=\s*1\s*\)')
        if (-not $declaration.Success) {
            $problems.Add("${relative}: no declare(strict_types=1)")
            continue
        }
        $namespace = [regex]::Match($text, '(?m)^namespace\s')
        if ($namespace.Success -and $namespace.Index -lt $declaration.Index) {
            $problems.Add("${relative}: declare(strict_types=1) after the namespace")
        }
    }

    return New-CheckResult -Name 'every src/ file declares strict_types' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-PhpstanRatchet {
    <#
    .SYNOPSIS
        PHPStan stays at level 6 and the ignore list does not grow.

    .DESCRIPTION
        phpstan.neon carries its own instruction: "Do not add new entries here".
        Each ignored error is a rule the analyser no longer enforces, so growth
        is a silent quality regression. Three entries were the accepted baseline
        at 3.3.0; a fourth needs a written justification and an edit of this
        number.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0
    $expectedIgnores = 3

    $config = Get-ProjectText 'phpstan.neon'
    if ($null -eq $config) {
        return New-CheckResult -Name 'PHPStan configuration keeps its ratchet' -Ok $false -Examined 0 `
            -Details @('phpstan.neon is missing')
    }

    $examined++
    if ($config -notmatch '(?m)^\s*level:\s*6\s*$') {
        $problems.Add('phpstan.neon: level is not 6')
    }

    $examined++
    if ($config -notmatch '(?m)^\s*-\s*src\s*$') {
        $problems.Add('phpstan.neon: src is not in paths')
    }

    $examined++
    $ignoreCount = ([regex]::Matches($config, '(?m)^\s+(?:message|identifier):')).Count
    if ($ignoreCount -gt $expectedIgnores) {
        $problems.Add("phpstan.neon: $ignoreCount ignore entries (baseline $expectedIgnores) - tighten the code instead of ignoring it")
    }

    return New-CheckResult -Name 'PHPStan configuration keeps its ratchet' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-CiGates {
    <#
    .SYNOPSIS
        The CI workflow still runs the four gates this project depends on.

    .DESCRIPTION
        Lint, static analysis, tests and the HTTP smoke run are the only
        automated proof that a push is safe. Removing or renaming one is a
        quality regression even when the workflow stays valid YAML.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0

    $workflow = Get-ProjectText '.github/workflows/ci.yml'
    if ($null -eq $workflow) {
        return New-CheckResult -Name 'CI still runs lint, phpstan, phpunit and smoke' -Ok $false -Examined 0 `
            -Details @('the CI workflow is missing')
    }

    $gates = @(
        @{ Name = 'php -l lint step'; Pattern = 'php -l' },
        @{ Name = 'phpstan analyse step'; Pattern = 'phpstan analyse' },
        @{ Name = 'phpunit step'; Pattern = 'phpunit' },
        @{ Name = 'HTTP smoke (api=search)'; Pattern = 'api=search' }
    )

    foreach ($gate in $gates) {
        $examined++
        Assert-RegexLiteral -Pattern $gate.Pattern -What 'ci gate'
        if ($workflow -notmatch $gate.Pattern) {
            $problems.Add("ci.yml: missing $($gate.Name)")
        }
    }

    return New-CheckResult -Name 'CI still runs lint, phpstan, phpunit and smoke' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-SecretHygiene {
    <#
    .SYNOPSIS
        Secret-shaped files have not appeared beyond the recorded baseline.

    .DESCRIPTION
        The files are never opened: only their names are read. The project ships
        no secret-shaped file at hand-over, so the baseline is empty and any
        finding is new. `.md.ini` is runtime state and lives outside git.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0

    $patterns = @(
        '^\.env$', '^\.env\.(?!example$|sample$|template$)',
        '\.key$', '^\.config\.php$', '^\.(htpasswd|httpauth)$',
        '^wp-config\.php$', '^id_(rsa|dsa|ecdsa|ed25519)',
        '\.(pem|pfx|p12|jks|keystore|ppk)$',
        '^\.(netrc|_netrc|git-credentials|npmrc|kdbx|ovpn)$',
        '\.sql\.php$'
    )
    $benign = @('cacert\.pem$', 'ca-bundle\.', '\.crt$', '\.min\.js$')

    foreach ($pattern in ($patterns + $benign)) {
        Assert-RegexLiteral -Pattern $pattern -What 'secret hygiene'
    }

    $baseline = @()

    foreach ($file in (Get-RepositoryFile -SecretScan -IncludeHidden)) {
        $examined++
        $relative = Get-RelativePath $file.FullName

        $skip = $false
        foreach ($pattern in $benign) { if ($file.Name -match $pattern) { $skip = $true; break } }
        if ($skip) { continue }

        $matched = $false
        foreach ($pattern in $patterns) { if ($file.Name -match $pattern) { $matched = $true; break } }
        if (-not $matched) { continue }

        $known = $false
        foreach ($entry in $baseline) { if ($relative -like $entry) { $known = $true; break } }
        if ($known) { continue }

        $problems.Add("secret-shaped file outside the baseline: $relative")
    }

    return New-CheckResult -Name 'no secret-shaped file outside the baseline' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-WikilinkContract {
    <#
    .SYNOPSIS
        The wikilink extension is registered where the engine looks for it.

    .DESCRIPTION
        Three things must stay true at once: the aggregate extension registers
        the parser and renderer, the toggle carries 'feature' => true so it
        enters the render fingerprint, and the sanitizer keeps the marker class.
        Break any one and links render as plain text, or render once and then
        serve stale HTML from the cache.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0

    $extension = Get-ProjectText 'src/Markdown/Extensions/MdViewerExtension.php'
    $examined++
    if ($null -eq $extension) {
        $problems.Add('src/Markdown/Extensions/MdViewerExtension.php: missing')
    }
    elseif ($extension -notmatch 'WikilinkParser' -or $extension -notmatch 'WikilinkRenderer') {
        $problems.Add('MdViewerExtension.php: wikilink parser or renderer is not registered')
    }
    elseif ($extension -notmatch 'FEATURE_WIKILINKS') {
        $problems.Add('MdViewerExtension.php: registration is not gated by FEATURE_WIKILINKS')
    }

    $examined++
    $defaults = Get-ProjectText 'config/defaults.php'
    if ($null -eq $defaults) {
        $problems.Add('config/defaults.php: missing')
    }
    elseif ($defaults -notmatch "'FEATURE_WIKILINKS'\s*=>\s*\[[^\]]*'feature'\s*=>\s*true") {
        $problems.Add("config/defaults.php: FEATURE_WIKILINKS is not marked 'feature' => true, so it never enters the render fingerprint")
    }

    $examined++
    $sanitizer = Get-ProjectText 'src/Markdown/HtmlSanitizer.php'
    if ($null -eq $sanitizer) {
        $problems.Add('src/Markdown/HtmlSanitizer.php: missing')
    }
    elseif ($sanitizer -notmatch "GLOBAL_ATTRS\s*=\s*\[[^\]]*'class'") {
        $problems.Add('HtmlSanitizer.php: class is not a global attribute, so md-wikilink would be stripped')
    }

    return New-CheckResult -Name 'wikilink extension follows the render contract' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-RenderCacheContract {
    <#
    .SYNOPSIS
        The corpus stamp is part of the render-cache key.

    .DESCRIPTION
        Wikilink existence depends on the set of documents, not only on the file
        being rendered. Without the stamp, creating a missing document leaves
        every page that links to it serving the "missing" marker until its own
        mtime changes.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0

    $examined++
    $cache = Get-ProjectText 'src/Markdown/RenderCache.php'
    if ($null -eq $cache) {
        $problems.Add('src/Markdown/RenderCache.php: missing')
    }
    elseif ($cache -notmatch 'function key\([^)]*corpusStamp') {
        $problems.Add('RenderCache.php: key() no longer accepts a corpus stamp')
    }

    $examined++
    $viewer = Get-ProjectText 'src/Http/Controllers/ViewerController.php'
    if ($null -eq $viewer) {
        $problems.Add('src/Http/Controllers/ViewerController.php: missing')
    }
    elseif ($viewer -notmatch '->key\([^)]*\$corpusStamp') {
        $problems.Add('ViewerController.php: the corpus stamp is not passed to the cache key')
    }

    return New-CheckResult -Name 'render cache key covers the document set' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems
}

function Test-ReleaseManifest {
    <#
    .SYNOPSIS
        Advisory: config/manifest.json is regenerated for the current version.

    .DESCRIPTION
        The manifest is a release artefact, generated by
        php tools/build-manifest.php. While it lags the code the updater refuses
        every update (a hash mismatch aborts the whole run), so the drift is
        worth a warning on every check - but it is not an error before a release.
    #>
    $problems = [System.Collections.Generic.List[string]]::new()
    $examined = 0

    $versionSource = Get-ProjectText 'src/Core/Version.php'
    $manifestRaw = Get-ProjectText 'config/manifest.json'
    if ($null -eq $versionSource -or $null -eq $manifestRaw) {
        return New-CheckResult -Name 'release manifest matches the version' -Ok $false -Examined 0 `
            -Details @('Version.php or the release manifest is missing')
    }

    $examined++
    $codeVersion = [regex]::Match($versionSource, "VERSION\s*=\s*'([0-9]+\.[0-9]+\.[0-9]+)'").Groups[1].Value
    $manifestVersion = ''
    $manifest = $null
    try { $manifest = $manifestRaw | ConvertFrom-Json -AsHashtable } catch { $manifest = $null }
    if ($manifest -is [System.Collections.IDictionary]) {
        $manifestVersion = [string] ($manifest['version'] ?? '')
    }

    if ($manifestVersion -eq '') {
        $problems.Add('config/manifest.json: no version field')
    }
    elseif ($manifestVersion -ne $codeVersion) {
        $problems.Add("manifest is $manifestVersion, code is $codeVersion - run php tools/build-manifest.php before the next release")
    }

    return New-CheckResult -Name 'release manifest matches the version' -Ok ($problems.Count -eq 0) -Examined $examined -Details $problems -Warning:($problems.Count -gt 0)
}

# ------------------------------------------------------------------- runner

$script:CheckFunctions = @(
    'Test-ProjectLayout'
    'Test-VersionConsistency'
    'Test-StrictTypes'
    'Test-PhpstanRatchet'
    'Test-CiGates'
    'Test-SecretHygiene'
    'Test-WikilinkContract'
    'Test-RenderCacheContract'
    'Test-ReleaseManifest'
)

$script:CheckNames = @()
foreach ($name in $script:CheckFunctions) { $script:CheckNames += $name }

Write-Host 'project doctrine check'
Write-Host "repository: $script:ProjectRoot"
Write-Host ''

$errors = 0
$warnings = 0
$notApplicable = 0
$voidChecks = 0

foreach ($name in $script:CheckFunctions) {
    $check = & $name
    Write-CheckResult -Check $check

    switch ($check.Kind) {
        'na'   { $notApplicable++ }
        'warn' { $warnings++ }
        'void' { $voidChecks++; $errors++ }
        'pass' { }
        default {
            if ($check.Warning -and -not $Strict) { $warnings++ } else { $errors++ }
        }
    }
}

Write-Host ''
Write-Host "checks: $($script:CheckFunctions.Count), errors: $errors, warnings: $warnings, not-applicable: $notApplicable"

if ($voidChecks -gt 0) {
    Write-Host "$voidChecks проверок сообщили ложный PASS (осмотрено 0 объектов) — это дефект чекера, а не проекта." -ForegroundColor Red
}

if ($errors -gt 0) {
    Write-Host 'Result: FAIL' -ForegroundColor Red
    exit 1
}

if ($warnings -gt 0) {
    Write-Host 'Result: PASS with warnings' -ForegroundColor Yellow
    exit 0
}

Write-Host 'Result: PASS' -ForegroundColor Green
exit 0
